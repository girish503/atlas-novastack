        dense_order = [r.document_id for r in dense_50]

        r_bm = next((idx for idx, d in enumerate(bm25_order, start=1) if d in exp_docs), None)
        r_dn = next((idx for idx, d in enumerate(dense_order, start=1) if d in exp_docs), None)

        valid_ranks = [r for r in (r_bm, r_dn) if r is not None]
        if valid_ranks:
            best_pre = min(valid_ranks)
            if 11 <= best_pre <= 50:
                # This is one of the 22 headroom cases
                # Check rank in System F
                res_f_top50 = pipeline.rerank_union(
                    query=c["query"],
                    top_k=50,
                    depth=50,
                    filters={"tenant_id": c.get("tenant_id")} if c.get("tenant_id") else None,
                )
                f_order = [r.document_id for r in res_f_top50]
                r_f = next((idx for idx, d in enumerate(f_order, start=1) if d in exp_docs), None)

