def _compute_hash(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()


def compute_dcg(relevances: list[int], k: int = 10) -> float:
    """Compute Discounted Cumulative Gain at rank k."""
    dcg = 0.0
    for i, rel in enumerate(relevances[:k], start=1):
        if rel > 0:
            dcg += rel / math.log2(i + 1)
    return dcg


def compute_idcg(num_relevant: int, k: int = 10) -> float:
    """Compute Ideal Discounted Cumulative Gain at rank k."""
    ideal_count = min(num_relevant, k)
    if ideal_count <= 0:
        return 0.0
    idcg = 0.0
    for i in range(1, ideal_count + 1):
        idcg += 1.0 / math.log2(i + 1)
    return idcg


def _calc_recall_at_k(doc_ids: list[str], expected_docs: set[str], k: int) -> float:
    if not expected_docs:
        return 0.0
    top_docs = set(doc_ids[:k])
    return len(top_docs.intersection(expected_docs)) / len(expected_docs)


def evaluate_system_run(
    results_per_case: list[dict[str, Any]],
) -> dict[str, Any]:
    """Calculate aggregate and category metrics for a single system run."""
    pos_cases = [c for c in results_per_case if c["is_positive"]]
    n_pos = len(pos_cases)

    rec_1 = [c["metrics"]["recall_at_1"] for c in pos_cases]
    rec_3 = [c["metrics"]["recall_at_3"] for c in pos_cases]
    rec_5 = [c["metrics"]["recall_at_5"] for c in pos_cases]
    rec_10 = [c["metrics"]["recall_at_10"] for c in pos_cases]
    mrr_list = [c["metrics"]["mrr"] for c in pos_cases]
    ndcg_list = [c["metrics"]["ndcg_at_10"] for c in pos_cases]

    total_forbidden = sum(c["forbidden_leaks_top_10"] for c in results_per_case)

    cat_metrics: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for c in pos_cases:
        cat = c["category"]
        cat_metrics[cat]["recall_at_10"].append(c["metrics"]["recall_at_10"])
        cat_metrics[cat]["mrr"].append(c["metrics"]["mrr"])
        cat_metrics[cat]["ndcg_at_10"].append(c["metrics"]["ndcg_at_10"])

    def _mean(v: list[float]) -> float:
        return round(sum(v) / len(v), 4) if v else 0.0

    aggregated_categories = {}
    for cat, m in sorted(cat_metrics.items()):
        aggregated_categories[cat] = {
            "cases_count": len(m["recall_at_10"]),
            "recall_at_10": _mean(m["recall_at_10"]),
            "mrr": _mean(m["mrr"]),
            "ndcg_at_10": _mean(m["ndcg_at_10"]),
        }

    return {
        "aggregate": {
            "positive_cases_count": n_pos,
            "recall_at_1": _mean(rec_1),
            "recall_at_3": _mean(rec_3),
            "recall_at_5": _mean(rec_5),
            "recall_at_10": _mean(rec_10),
            "mrr": _mean(mrr_list),
            "ndcg_at_10": _mean(ndcg_list),
            "forbidden_leaks_top_10": total_forbidden,
        },
        "categories": aggregated_categories,
    }


